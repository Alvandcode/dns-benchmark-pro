"""HTML report + latency chart (average AND p95, uses matplotlib)."""

from __future__ import annotations

import html
from pathlib import Path


def _ensure_parent(file: Path) -> Path:
    file = Path(file)
    file.parent.mkdir(parents=True, exist_ok=True)
    return file


def _try_chart(results, out_dir: Path):
    """Best-effort grouped bar chart of average + p95. Returns filename or None."""
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except Exception:
        return None
    try:
        labels = [str(r.get("ip", "?")) for r in results]
        avg = [float(r.get("average", 0) or 0) for r in results]
        p95 = [float(r.get("p95", 0) or 0) for r in results]
        x = range(len(labels))
        width = 0.38
        fig, ax = plt.subplots(figsize=(max(8, len(labels) * 2), 4))
        ax.bar([i - width / 2 for i in x], avg, width, label="avg ms")
        ax.bar([i + width / 2 for i in x], p95, width, label="p95 ms")
        ax.set_xticks(list(x), labels, rotation=15)
        ax.set_title("DNS Benchmark - Average vs P95 latency (ms)")
        ax.set_ylabel("ms")
        ax.legend()
        fig.tight_layout()
        chart = out_dir / "chart.png"
        fig.savefig(chart, dpi=120)
        plt.close(fig)
        return chart.name
    except Exception:
        return None


def generate_html_report(results, path="results/report.html"):
    if not results:
        raise ValueError("no data to export (empty result list)")
    file = _ensure_parent(Path(path))
    out_dir = file.parent

    chart_name = _try_chart(results, out_dir)
    img_tag = f'<img src="{html.escape(chart_name)}" alt="latency chart"/>' if chart_name else "<p><em>Chart unavailable (matplotlib missing).</em></p>"

    rows = []
    for r in results:
        errs = r.get("errors", {})
        if isinstance(errs, dict) and errs:
            err_txt = "; ".join(f"{html.escape(str(k))}x{int(v)}" for k, v in sorted(errs.items()))
        else:
            err_txt = "-"
        rows.append(
            "<tr>"
            f"<td>{html.escape(str(r.get('ip', '')))}</td>"
            f"<td>{html.escape(str(r.get('protocol', '')))}</td>"
            f"<td>{html.escape(str(r.get('score', '')))}</td>"
            f"<td>{html.escape(str(r.get('grade', '')))}</td>"
            f"<td>{html.escape(str(round(float(r.get('average', 0) or 0), 2)))}</td>"
            f"<td>{html.escape(str(round(float(r.get('median', 0) or 0), 2)))}</td>"
            f"<td>{html.escape(str(round(float(r.get('p95', 0) or 0), 2)))}</td>"
            f"<td>{html.escape(str(round(float(r.get('packet_loss', 0) or 0), 2)))}</td>"
            f"<td>{err_txt}</td>"
            "</tr>"
        )

    doc = f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8"/>
<meta name="viewport" content="width=device-width, initial-scale=1"/>
<title>DNS Benchmark Report</title>
<style>
body{{font-family:system-ui,Segoe UI,Tahoma,sans-serif;margin:24px}}
table{{border-collapse:collapse;width:100%}}
th,td{{border:1px solid #999;padding:6px 10px;text-align:center}}
th{{background:#f0f0f0}}
</style>
</head>
<body>
<h1>DNS Benchmark Report</h1>
<p>Lower average/p95 is better. Score 0-100, grade A+..F. Only NOERROR counts as success.</p>
<table>
<tr><th>Server</th><th>Proto</th><th>Score</th><th>Grade</th><th>Avg ms</th><th>Median ms</th><th>P95 ms</th><th>Loss %</th><th>Errors</th></tr>
{''.join(rows)}
</table>
<h2>Latency chart (avg vs p95)</h2>
{img_tag}
<p><small>Generated by dns-benchmark-pro. Each run overwrites this file.</small></p>
</body>
</html>
"""
    file.write_text(doc, encoding="utf-8")
    return file
